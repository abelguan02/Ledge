import AppKit

@main @MainActor struct CollectionManagementModelTests {
    static func main() async throws {
        NSApplication.shared.setActivationPolicy(.prohibited)
        let root = FileManager.default.temporaryDirectory.appendingPathComponent("dump-collection-model-\(UUID())")
        defer { try? FileManager.default.removeItem(at: root) }
        let library = try Library(root: root)
        let first = await library.index.currentCollection
        let second = try await library.createCollection("same")
        let model = WorkbenchModel(library: library)
        await model.refresh()
        model.manageCollections()
        precondition(model.collectionPage == .manager && model.collectionSelection.isEmpty)
        model.showCollectionConfirmation([first, second.id]); await model.waitForWrites()
        precondition(model.collectionPage == .confirmation)
        model.collectionEscape()
        precondition(model.collectionPage == .manager && model.collectionSelection == [first, second.id])
        model.collectionEscape()
        precondition(model.collectionPage == .closed && model.collectionSelection.isEmpty)
        model.showCollectionConfirmation([first], direct: true); await model.waitForWrites()
        model.collectionEscape(); precondition(model.collectionPage == .closed)
        model.showCollectionConfirmation([first, second.id]); await model.waitForWrites()
        _ = try await library.importText("arrived after confirmation", collection: first)
        model.deleteSelectedCollections()
        model.closeCollectionMenu()
        precondition(model.collectionDeleting && model.collectionPage == .confirmation)
        await model.waitForWrites()
        precondition(model.collectionStatus == "内容有变化，请再确认一次。" && model.index.items.count == 1)
        model.deleteSelectedCollections(); await model.waitForWrites()
        precondition(model.collectionPage == .manager && model.collectionDeletedCount == 2 && model.index.items.isEmpty)
        precondition(model.index.collections.count == 1 && model.collectionSelection.isEmpty)
        model.undo(); await model.waitForWrites()
        precondition(model.index.items.count == 1 && model.index.collections.map(\.id) == [first, second.id])
        precondition(model.index.currentCollection == second.id)
        try await model.shutdown()
        let cleanupRoot = root.appendingPathComponent("cleanup-warning")
        let cleanupLibrary = try Library(root: cleanupRoot)
        let cleanupModel = WorkbenchModel(library: cleanupLibrary)
        let aGroup = await cleanupLibrary.index.currentCollection
        let a = try await cleanupLibrary.importText("old undo", collection: aGroup)
        let bGroup = try await cleanupLibrary.createCollection("second")
        let b = try await cleanupLibrary.importText("current undo", collection: bGroup.id)
        await cleanupModel.refresh()
        cleanupModel.showCollectionConfirmation([aGroup]); await cleanupModel.waitForWrites()
        cleanupModel.deleteSelectedCollections(); await cleanupModel.waitForWrites()
        let oldDirectory = cleanupRoot.appendingPathComponent("trash/\(a.id)")
        let held = cleanupRoot.appendingPathComponent("held")
        try FileManager.default.moveItem(at: oldDirectory, to: held)
        try FileManager.default.createSymbolicLink(at: oldDirectory, withDestinationURL: held)
        cleanupModel.showCollectionConfirmation([bGroup.id]); await cleanupModel.waitForWrites()
        cleanupModel.deleteSelectedCollections(); await cleanupModel.waitForWrites()
        precondition(cleanupModel.collectionPage == .manager && cleanupModel.collectionDeletedCount == 1)
        precondition(cleanupModel.index.items.isEmpty && cleanupModel.index.undo?.items.map(\.id) == [b.id])
        precondition(!cleanupModel.collectionDeleteFailed && !cleanupModel.collectionDeleting)
        precondition(cleanupModel.message.hasPrefix("收集区已删除，但文件清理未完成"), "post-commit warning must reach the visible canvas message banner")
        try FileManager.default.removeItem(at: oldDirectory)
        try FileManager.default.moveItem(at: held, to: oldDirectory)
        cleanupModel.undo(); await cleanupModel.waitForWrites()
        precondition(cleanupModel.items.map(\.id) == [b.id])
        try await cleanupModel.shutdown()
        print("PASS manager/direct cancel, selection retention, delete dismissal lock, live-content revalidation, batch success and shared undo")
        print("PASS post-commit cleanup warning is visible without falsely reporting failed deletion; current undo remains available")
    }
}
